"""Render a Model as Mermaid C4 or Structurizr DSL text."""
from __future__ import annotations

import re

from .model import Model


def _q(s: str) -> str:
    return '"' + str(s).replace("\\", "\\\\").replace('"', "'") + '"'


class _Ids:
    """Stable, unique, identifier-safe ids."""

    def __init__(self) -> None:
        self.seen: dict[str, str] = {}
        self.used: set[str] = set()

    def get(self, key: str, prefix: str = "") -> str:
        k = prefix + key
        if k in self.seen:
            return self.seen[k]
        base = re.sub(r"\W", "_", k).strip("_") or "x"
        if base[0].isdigit():
            base = "n_" + base
        cand, i = base, 2
        while cand in self.used:
            cand = f"{base}_{i}"
            i += 1
        self.used.add(cand)
        self.seen[k] = cand
        return cand


LEVELS = ("context", "container", "component", "all")


def mermaid(m: Model, level: str = "all") -> str:
    ids = _Ids()
    blocks: list[str] = []
    sysid = ids.get(m.system, "sys_")
    ext_all = m.externals()
    cont_ext = m.container_externals()

    if level in ("context", "all"):
        L = ["%% System context", "C4Context", f"  title System context: {m.system}",
             f"  System({sysid}, {_q(m.system)}, {_q(f'{len(m.containers)} containers, {len(m.components)} components')})"]
        for e in ext_all:
            L.append(f"  System_Ext({ids.get(e, 'ext_')}, {_q(e)}, \"third-party package\")")
        for e in ext_all:
            L.append(f"  Rel({sysid}, {ids.get(e, 'ext_')}, \"imports\")")
        blocks.append("\n".join(L))

    if level in ("container", "all"):
        L = ["%% Containers", "C4Container", f"  title Containers: {m.system}", f"  System_Boundary({sysid}_b, {_q(m.system)}) {{"]
        for c in m.containers:
            n = sum(1 for x in m.components if x.container == c.id)
            L.append(f"    Container({ids.get(c.id, 'c_')}, {_q(c.name)}, {_q(c.technology)}, {_q(f'{n} modules, path {c.path}')})")
        L.append("  }")
        used_ext = sorted({e for v in cont_ext.values() for e in v})
        for e in used_ext:
            L.append(f"  System_Ext({ids.get(e, 'ext_')}, {_q(e)}, \"third-party package\")")
        for a, b in m.container_relations():
            L.append(f"  Rel({ids.get(a, 'c_')}, {ids.get(b, 'c_')}, \"imports\")")
        for c, exts in cont_ext.items():
            for e in exts:
                L.append(f"  Rel({ids.get(c, 'c_')}, {ids.get(e, 'ext_')}, \"imports\")")
        blocks.append("\n".join(L))

    if level in ("component", "all"):
        for c in m.containers:
            mine = [x for x in m.components if x.container == c.id]
            inside = {x.id for x in mine}
            rels = [r for r in m.relations if r.src in inside or r.dst in inside]
            outside = sorted({r.dst for r in rels if r.dst not in inside} | {r.src for r in rels if r.src not in inside})
            byid = {x.id: x for x in m.components}
            L = [f"%% Components of {c.name}", "C4Component", f"  title Components: {c.name}",
                 f"  Container_Boundary({ids.get(c.id, 'c_')}_b, {_q(c.name)}) {{"]
            for x in mine:
                L.append(f"    Component({ids.get(x.id, 'm_')}, {_q(x.name)}, {_q(x.technology)}, {_q(x.path)})")
            L.append("  }")
            for o in outside:
                L.append(f"  Component_Ext({ids.get(o, 'm_')}, {_q(byid[o].name)}, {_q(byid[o].technology)}, {_q('in ' + byid[o].container)})")
            for r in rels:
                L.append(f"  Rel({ids.get(r.src, 'm_')}, {ids.get(r.dst, 'm_')}, {_q(r.kind)})")
            blocks.append("\n".join(L))
    return "\n\n".join(blocks) + "\n"


def dsl(m: Model) -> str:
    ids = _Ids()
    sysid = ids.get(m.system, "sys_")
    L = [f"workspace {_q(m.system)} {{", "  model {",
         f"    {sysid} = softwareSystem {_q(m.system)} \"Generated by c4-live\" {{"]
    for c in m.containers:
        L.append(f"      {ids.get(c.id, 'c_')} = container {_q(c.name)} {_q(c.path)} {_q(c.technology)} {{")
        for x in m.components:
            if x.container == c.id:
                L.append(f"        {ids.get(x.id, 'm_')} = component {_q(x.name)} {_q(x.path)} {_q(x.technology)}")
        L.append("      }")
    L.append("    }")
    for e in m.externals():
        L.append(f"    {ids.get(e, 'ext_')} = softwareSystem {_q(e)} \"third-party package\" \"External\"")
    # container-level relationships first so implied relationships from the component ones do not duplicate them
    for a, b in m.container_relations():
        L.append(f"    {ids.get(a, 'c_')} -> {ids.get(b, 'c_')} \"imports\"")
    for c, exts in m.container_externals().items():
        for e in exts:
            L.append(f"    {ids.get(c, 'c_')} -> {ids.get(e, 'ext_')} \"imports\"")
    for r in m.relations:
        L.append(f"    {ids.get(r.src, 'm_')} -> {ids.get(r.dst, 'm_')} {_q(r.kind)}")
    L += ["  }", "  views {",
          f"    systemContext {sysid} \"Context\" {{", "      include *", "      autolayout lr", "    }",
          f"    container {sysid} \"Containers\" {{", "      include *", "      autolayout lr", "    }"]
    for c in m.containers:
        key = "Components_" + re.sub(r"\W", "_", c.id)
        L += [f"    component {ids.get(c.id, 'c_')} {_q(key)} {{", "      include *", "      autolayout lr", "    }"]
    L += ["    styles {", "      element \"External\" {", "        background #999999", "        color #ffffff", "      }", "    }", "  }", "}"]
    return "\n".join(L) + "\n"
